#!/usr/bin/env node

const fs = require('fs');
const path = require('path');

const repoRoot = path.resolve(__dirname, '..');
const websiteDir = path.join(repoRoot, 'website');
const localeConfigPath = path.join(websiteDir, 'seo', 'locales.json');
const pageConfigPath = path.join(websiteDir, 'seo', 'pages.json');
const sitemapPath = path.join(websiteDir, 'sitemap.xml');

const START = '  <!-- SEO_ALTERNATES_START -->';
const END = '  <!-- SEO_ALTERNATES_END -->';

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

function normalizeBaseUrl(url) {
  return url.replace(/\/+$/, '');
}

function absoluteUrl(baseUrl, pagePath) {
  const normalizedPath = pagePath.startsWith('/') ? pagePath : `/${pagePath}`;
  return `${baseUrl}${normalizedPath}`;
}

function pagePathToFile(pagePath) {
  if (pagePath === '/') {
    return path.join(websiteDir, 'index.html');
  }
  if (pagePath.endsWith('/')) {
    return path.join(websiteDir, pagePath, 'index.html');
  }
  return path.join(websiteDir, pagePath);
}

function escapeXml(value) {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function buildLocaleMap(locales) {
  return new Map(locales.map((locale) => [locale.code, locale]));
}

function buildAlternates(page, localeMap, baseUrl, xDefaultLocale) {
  const entries = Object.entries(page.availableLocales || {}).map(([localeCode, pagePath]) => {
    const locale = localeMap.get(localeCode);
    if (!locale) {
      throw new Error(`Unknown locale "${localeCode}" on page "${page.id}"`);
    }
    return {
      localeCode,
      hreflang: locale.hreflang,
      href: absoluteUrl(baseUrl, pagePath),
      path: pagePath
    };
  });

  const xDefault = entries.find((entry) => entry.localeCode === xDefaultLocale) || entries[0];
  return { entries, xDefault };
}

function buildSeoBlock(canonicalUrl, alternates) {
  const lines = [
    START,
    `  <link rel="canonical" href="${canonicalUrl}">`,
    '  <!-- Multilingual SEO alternates are generated by scripts/generate-website-seo.js. -->'
  ];

  for (const alternate of alternates.entries) {
    lines.push(`  <link rel="alternate" hreflang="${alternate.hreflang}" href="${alternate.href}">`);
  }

  if (alternates.xDefault) {
    lines.push(`  <link rel="alternate" hreflang="x-default" href="${alternates.xDefault.href}">`);
  }

  lines.push(END);
  return `${lines.join('\n')}\n`;
}

function updateHtmlSeoBlock(filePath, canonicalUrl, alternates) {
  const html = fs.readFileSync(filePath, 'utf8');
  const block = buildSeoBlock(canonicalUrl, alternates);
  let nextHtml;

  if (html.includes(START) && html.includes(END)) {
    const pattern = new RegExp(`${START}[\\s\\S]*?${END}\\n?`);
    nextHtml = html.replace(pattern, block);
  } else {
    nextHtml = html.replace(/^  <link rel="canonical" href="[^"]+">\n/m, block);
  }

  if (nextHtml === html) {
    const hasGeneratedBlock = html.includes(START) && html.includes(END);
    const hasCanonical = html.includes(`<link rel="canonical" href="${canonicalUrl}">`);
    if (!hasGeneratedBlock || !hasCanonical) {
      throw new Error(`Could not update canonical/hreflang block in ${filePath}`);
    }
    return;
  }

  fs.writeFileSync(filePath, nextHtml);
}

function buildSitemap(pages, localeMap, baseUrl, xDefaultLocale) {
  const lines = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">'
  ];

  for (const page of pages) {
    const alternates = buildAlternates(page, localeMap, baseUrl, xDefaultLocale);

    for (const alternate of alternates.entries) {
      lines.push('  <url>');
      lines.push(`    <loc>${escapeXml(alternate.href)}</loc>`);
      for (const sibling of alternates.entries) {
        lines.push(`    <xhtml:link rel="alternate" hreflang="${escapeXml(sibling.hreflang)}" href="${escapeXml(sibling.href)}" />`);
      }
      if (alternates.xDefault) {
        lines.push(`    <xhtml:link rel="alternate" hreflang="x-default" href="${escapeXml(alternates.xDefault.href)}" />`);
      }
      if (page.changefreq) {
        lines.push(`    <changefreq>${escapeXml(page.changefreq)}</changefreq>`);
      }
      if (page.priority) {
        lines.push(`    <priority>${escapeXml(page.priority)}</priority>`);
      }
      lines.push('  </url>');
    }
  }

  lines.push('</urlset>');
  return `${lines.join('\n')}\n`;
}

function validateLocaleCoverage(locales) {
  const localeDirs = new Set(
    fs.readdirSync(path.join(repoRoot, '_locales'), { withFileTypes: true })
      .filter((entry) => entry.isDirectory())
      .map((entry) => entry.name)
  );

  const missing = locales
    .filter((locale) => !localeDirs.has(locale.chromeLocale))
    .map((locale) => locale.chromeLocale);

  if (missing.length > 0) {
    throw new Error(`Website SEO locale config references missing extension locales: ${missing.join(', ')}`);
  }
}

function validatePages(pages, localeMap) {
  for (const page of pages) {
    const localeEntries = Object.entries(page.availableLocales || {});
    if (localeEntries.length === 0) {
      throw new Error(`Page "${page.id}" has no availableLocales`);
    }

    for (const [localeCode, pagePath] of localeEntries) {
      if (!localeMap.has(localeCode)) {
        throw new Error(`Page "${page.id}" references unknown locale "${localeCode}"`);
      }

      const filePath = pagePathToFile(pagePath);
      if (!fs.existsSync(filePath)) {
        throw new Error(`Page "${page.id}" locale "${localeCode}" points to a missing file: ${filePath}`);
      }
    }
  }
}

function main() {
  const localeConfig = readJson(localeConfigPath);
  const pageConfig = readJson(pageConfigPath);
  const baseUrl = normalizeBaseUrl(process.env.WEBSITE_BASE_URL || pageConfig.baseUrl);
  const localeMap = buildLocaleMap(localeConfig.locales);

  validateLocaleCoverage(localeConfig.locales);
  validatePages(pageConfig.pages, localeMap);

  for (const page of pageConfig.pages) {
    const alternates = buildAlternates(page, localeMap, baseUrl, localeConfig.xDefaultLocale);

    for (const alternate of alternates.entries) {
      const filePath = pagePathToFile(alternate.path);
      updateHtmlSeoBlock(filePath, alternate.href, alternates);
    }
  }

  fs.writeFileSync(
    sitemapPath,
    buildSitemap(pageConfig.pages, localeMap, baseUrl, localeConfig.xDefaultLocale)
  );

  console.log(`Generated multilingual SEO metadata for ${pageConfig.pages.length} pages.`);
}

main();
