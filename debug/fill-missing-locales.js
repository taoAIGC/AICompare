function cloneEntry(entry, message) {
  const out = {};
  if (typeof message !== 'string') {
    throw new Error(`Missing translated message for key: ${JSON.stringify(entry)}`);
  }
  out.message = message;
  if (entry.description) out.description = entry.description;
  if (entry.placeholders) out.placeholders = entry.placeholders;
  return out;
}

function replaceAll(input, replacements) {
  let output = input;
  for (const [from, to] of replacements) {
    output = output.split(from).join(to);
  }
  return output;
}

