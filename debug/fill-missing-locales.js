function translateMessage(lang, key) {
  if (lang === 'zh_TW') {
    return buildZhTW()[key];
  }
  if (injectBundles[lang]) {
    if (injectBundles[lang].direct[key]) return injectBundles[lang].direct[key];
    if (injectFocusTargets[key]) {
      const target = injectBundles[lang].targets[injectFocusTargets[key]];
      return injectPasteKeys.has(key)
        ? injectBundles[lang].focusPaste(target)
        : injectBundles[lang].focus(target);
    }
  }
  const directHit = direct[lang][key];
  if (directHit) return directHit;
  const actionHit = patternSets[lang]?.actions?.[key];
  if (actionHit) return actionHit;
  return null;
}

const missingByLang = {};

for (const lang of targetLangs) {
  const file = path.join(localesDir, lang, 'messages.json');
  const current = JSON.parse(fs.readFileSync(file, 'utf8'));
  const next = {};
  const missing = [];
  const zhTWAll = lang === 'zh_TW' ? buildZhTW() : null;

  for (const [key, enEntry] of Object.entries(en)) {
    if (zhTWAll) {
      next[key] = cloneEntry(enEntry, zhTWAll[key]);
      continue;
    }
    if (current[key]) {
      next[key] = current[key];
      continue;
    }

    const translatedMessage = translateMessage(lang, key);
    if (!translatedMessage) {
      missing.push(key);
      continue;
    }

    next[key] = cloneEntry(enEntry, translatedMessage);
  }

  if (missing.length) {
    missingByLang[lang] = missing;
    continue;
  }

  fs.writeFileSync(file, JSON.stringify(next, null, 2) + '\n');
}

if (Object.keys(missingByLang).length) {
  for (const [lang, keys] of Object.entries(missingByLang)) {
    console.error(`## ${lang} missing ${keys.length}`);
    console.error(keys.join(', '));
  }
  process.exit(1);
}

